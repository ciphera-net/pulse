#!/usr/bin/env node
/**
 * Generates lib/timezone-countries.gen.ts: IANA timezone → ISO 3166-1 country code, for the
 * flag beside each row of the Locations panel's Timezones tab (PULSE-170).
 *
 * Source: IANA tzdata, the only authority on which country a zone belongs to.
 *   - zone.tab  — every zone with the ONE country it is listed under.
 *   - backward  — legacy link names (Europe/Kiev → Europe/Kyiv, Asia/Calcutta → Asia/Kolkata).
 *                 Browsers still SEND these: Chrome reports Asia/Calcutta even when the OS says
 *                 Asia/Kolkata (the 21-09-2026 site-timezone incident), so a map without them
 *                 misses real visitors.
 * A zone.tab entry always wins over a link, so a link never overrides a zone's own country.
 * Zones that belong to no country (Etc/*, UTC, Factory) are absent: no flag is the correct
 * answer for them, not a guess.
 *
 * Usage (run by hand when tzdata changes; the output is committed, so builds need no network):
 *   node scripts/generate-timezone-countries.mjs            # downloads tzdata-latest from IANA
 *   node scripts/generate-timezone-countries.mjs <tzdir>    # a directory with zone.tab + backward + version
 */

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const OUT = join(ROOT, 'lib/timezone-countries.gen.ts')

function tzdataDir() {
  if (process.argv[2]) return process.argv[2]
  const dir = mkdtempSync(join(tmpdir(), 'tzdata-'))
  const tarball = join(dir, 'tzdata.tar.gz')
  execFileSync('curl', ['-fsSL', '-o', tarball, 'https://data.iana.org/time-zones/tzdata-latest.tar.gz'])
  execFileSync('tar', ['-xzf', tarball, '-C', dir, 'zone.tab', 'backward', 'version'])
  return dir
}

function dataLines(text) {
  return text.split('\n').filter((l) => l.trim() !== '' && !l.startsWith('#'))
}

const dir = tzdataDir()
const version = readFileSync(join(dir, 'version'), 'utf8').trim()

/** @type {Map<string, string>} */
const map = new Map()
for (const line of dataLines(readFileSync(join(dir, 'zone.tab'), 'utf8'))) {
  const [code, , zone] = line.split('\t')
  if (!/^[A-Z]{2}$/.test(code) || !zone) throw new Error(`unexpected zone.tab line: ${line}`)
  map.set(zone, code)
}
const zoneTabCount = map.size

let linkCount = 0
for (const line of dataLines(readFileSync(join(dir, 'backward'), 'utf8'))) {
  const fields = line.split(/\s+/)
  if (fields[0] !== 'Link') continue
  const [, target, name] = fields
  if (map.has(name)) continue
  const code = map.get(target)
  if (!code) continue
  map.set(name, code)
  linkCount++
}

const entries = [...map.entries()].sort(([a], [b]) => a.localeCompare(b))
const body = entries.map(([zone, code]) => `  '${zone}': '${code}',`).join('\n')

writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-timezone-countries.mjs from IANA tzdata ${version}.
// Do not edit by hand: re-run the script. ${zoneTabCount} zones from zone.tab + ${linkCount} legacy links from backward.
// Zones that belong to no country (Etc/*, UTC) are deliberately absent.

export const TZDATA_VERSION = '${version}'

export const TIMEZONE_COUNTRY: Readonly<Record<string, string>> = {
${body}
}
`,
)
console.log(`[generate-timezone-countries] tzdata ${version}: ${zoneTabCount} zones + ${linkCount} links → ${OUT}`)

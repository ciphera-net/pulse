const hex = (s: string) => Uint8Array.from(Buffer.from(s, 'hex'))
const toHex = (b: Uint8Array) => Buffer.from(b).toString('hex')
/** SHA-256 as the server computes sealed_hash, independent of the code under test. */
const sha256Hex = (b: Uint8Array) => createHash('sha256').update(b).digest('hex')
/** I2OSP(len, 2) || bytes || zeros to 512, built here from the bytes and not by the code under test. */
const layout = (bytes: Uint8Array) => {
  const pt = new Uint8Array(PADDED_SIZE)
  pt[0] = bytes.length >> 8
  pt[1] = bytes.length & 0xff
  pt.set(bytes, 2)
  return toHex(pt)
}

async function vaultKey(vmkHex: string): Promise<VaultKey> {
  return (await crypto.subtle.importKey('raw', hex(vmkHex), 'HKDF', false, ['deriveKey'])) as VaultKey
}

const identityCache = new Map<string, Promise<TeamIdentity>>()
function identity(label: string): Promise<TeamIdentity> {
  const cached = identityCache.get(label)
  if (cached) return cached
  const vi = v.identities.find((i) => i.label === label)
  if (!vi) throw new Error(`no identity ${label}`)
  const made = (async () => openIdentityEnvelope(vaultOpsFor(await vaultKey(vi.vmk)), hex(vi.sealed_private_key)))()
  identityCache.set(label, made)
  return made
}
const byLabel = (label: string) => {
  const found = v.identities.find((i) => i.label === label)
  if (!found) throw new Error(`no identity ${label}`)
  return found
}

/** A row of the given kind opened with the code's own opener for that kind. */
async function openAs(kind: 'email' | 'name', p: OpenEmailParams): Promise<string | null> {
  return kind === 'email' ? openEmail(p) : openName(p)
}


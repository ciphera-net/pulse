// @vitest-environment node
//
// The email kind of the team-names construction (design §16.2) against vectors/team-emails-v1.json:
// twelve seals over two teams and all six ordered pairs of three people (a typical address, the shortest,
// plus-addressed, three-byte UTF-8 on both sides, upper case kept, a subdomain, 254 bytes of ASCII and of
// two-byte UTF-8, four-byte UTF-8, every atext symbol), every identity's envelope, every row's email tag,
// and the negatives: each binding, each refusal before any cryptography, each malformed plaintext, fourteen
// well-formed seals of addresses the check refuses (which the sealer must refuse too), a row of each kind
// opened as the other, and each tag binding. The file was generated by the same standard-library Go
// reference that made team-names-v1.json, and every seal in it equals Cloudflare CIRCL's output for the
// same inputs; the server carries the same file, pinned by the same SHA-256.


describe('the team-emails-v1 vector file', () => {
  it('is the pinned file, and its constants are this code’s', () => {
    expect(createHash('sha256').update(readFileSync(FILE)).digest('hex')).toBe(FILE_SHA256)
    expect(v.suite).toEqual({ kem_id: TEAM_NAMES_SUITE.kemId, kdf_id: TEAM_NAMES_SUITE.kdfId, aead_id: TEAM_NAMES_SUITE.aeadId })
    expect([v.info_label, v.tag_label, v.names_info_label, v.identity_context]).toEqual([EMAIL_INFO_LABEL, EMAIL_TAG_LABEL, INFO_LABEL, IDENTITY_CONTEXT])
    expect([v.wire_version, v.padded_size, v.max_email_bytes, v.sealed_size]).toEqual([WIRE_VERSION, PADDED_SIZE, MAX_EMAIL_BYTES, SEALED_SIZE])
    // A list that lost its entries would generate no tests below and pass by never looking.
    expect(v.seals).toHaveLength(12)
    expect(new Set(v.seals.map((s) => s.team_id)).size).toBe(2)
    expect(new Set(v.seals.map((s) => `${s.sender}>${s.recipient}`)).size).toBe(6)
    expect(Math.max(...v.seals.map((s) => hex(s.email_utf8).length))).toBe(MAX_EMAIL_BYTES)
    expect(v.open_negatives).toHaveLength(17)
    expect(v.address_negatives).toHaveLength(14)
    expect(v.cross_kind_negatives.map((n) => `${n.sealed_as}>${n.open_as}`).sort()).toEqual(['email>name', 'name>email'])
    expect(v.tag_negatives).toHaveLength(6)
    expect(v.envelope_negatives).toHaveLength(2)
    expect(new Set(v.open_negatives.map((n) => n.outcome))).toEqual(new Set(['open_fails', 'refused_version', 'refused_length', 'no_email']))
  })
})

describe('identities and their envelopes', () => {
  it.each(v.identities.map((i) => [i.label, i] as const))('%s: the envelope opens under the vault key to 0x01 || d || pub || tag_secret', async (_l, vi) => {
    const vault = vaultOpsFor(await vaultKey(vi.vmk))
    const pt = await vault.open(IDENTITY_CONTEXT, hex(vi.sealed_private_key))
    expect(toHex(pt)).toBe(vi.envelope_plaintext)
    expect(toHex(pt)).toBe(`01${vi.private_key}${vi.public_key}${vi.tag_secret}`)
    expect(hex(vi.sealed_private_key).length).toBe(IDENTITY_ENVELOPE_SIZE)
  })

  it.each(v.identities.map((i) => [i.label, i] as const))('%s: the session identity carries the pub, the key id and a non-extractable key', async (label, vi) => {
    const id = await identity(label)
    expect(toHex(id.publicKey)).toBe(vi.public_key)
    expect(toHex(id.keyId)).toBe(vi.key_id)
    expect(toHex(await keyIdOf(hex(vi.public_key)))).toBe(vi.key_id)
    expect(id.privateKey.extractable).toBe(false)
    expect(id.privateKey.usages).toEqual(['deriveBits'])
  })

  it('pairs each envelope’s d with its pub (two Diffie-Hellmans agree)', async () => {
    const d = await identity('D')
    const ev = byLabel('E')
    const ePriv = await importPrivateKey(TEAM_NAMES_SUITE, hex(ev.private_key), hex(ev.public_key))
    const de = await crypto.subtle.deriveBits({ name: 'ECDH', public: await importPublicKey(TEAM_NAMES_SUITE, hex(ev.public_key)) }, d.privateKey, 256)
    const ed = await crypto.subtle.deriveBits({ name: 'ECDH', public: await importPublicKey(TEAM_NAMES_SUITE, d.publicKey) }, ePriv, 256)
    expect(toHex(new Uint8Array(de))).toBe(toHex(new Uint8Array(ed)))
  })

  it.each(v.envelope_negatives.map((n) => [n.description, n] as const))('refuses %s', async (_d, n) => {
    const vault = vaultOpsFor(await vaultKey(n.vmk))
    await expect(vault.open(n.context, hex(byLabel(n.envelope_of).sealed_private_key))).rejects.toThrow()
    if (n.context === IDENTITY_CONTEXT) {
      await expect(openIdentityEnvelope(vault, hex(byLabel(n.envelope_of).sealed_private_key))).rejects.toMatchObject({
        code: 'team_names/identity_unopenable',
      })
    }
  })
})

describe('the twelve seals', () => {
  it.each(v.seals.map((s, i) => [i, s.description, s] as const))('seal %i (%s): info, plaintext, tag and every byte of the row', async (_i, _d, s) => {
    const info = emailInfo(s.team_id, s.sender_id, s.recipient_id)
    expect(toHex(info)).toBe(s.info)
    expect(info.length).toBe(69)
    expect(toHex(new TextEncoder().encode(s.email))).toBe(s.email_utf8)
    expect(checkEmail(s.email)).toBe(s.email)
    // The name's padded layout, as design §16.2 says, built two ways.
    expect(layout(hex(s.email_utf8))).toBe(s.plaintext)
    expect(toHex(padName(s.email))).toBe(s.plaintext)

    const sender = await identity(s.sender)
    const recipient = byLabel(s.recipient)
    expect(toHex(sender.keyId)).toBe(s.sender_key_id)
    expect(toHex(await keyIdOf(hex(recipient.public_key)))).toBe(s.recipient_key_id)

    const ephemeral = {
      privateKey: await importPrivateKey(TEAM_NAMES_SUITE, hex(s.ephemeral_private_key), hex(s.enc)),
      publicKey: hex(s.enc),
    }
    const out = await sealEmailWithEphemeralKeyForTesting(
      {
        teamId: s.team_id,
        senderId: s.sender_id,
        recipientId: s.recipient_id,
        email: s.email,
        sender,
        recipientPublicKey: hex(recipient.public_key),
        recipientKeyId: hex(s.recipient_key_id),
      },
      ephemeral,
    )
    expect(toHex(out.trace.sharedSecret)).toBe(s.shared_secret)
    expect(toHex(out.trace.key)).toBe(s.key)
    expect(toHex(out.trace.baseNonce)).toBe(s.base_nonce)
    expect(toHex(out.enc)).toBe(s.enc)
    expect(toHex(out.sealed)).toBe(s.sealed)
    expect(out.sealed.length).toBe(SEALED_SIZE)
    expect(toHex(out.emailTag)).toBe(s.email_tag)
    expect(out.emailTag.length).toBe(EMAIL_TAG_SIZE)
    expect(sha256Hex(hex(s.sealed))).toBe(s.sealed_hash)

    const tagKey = await importTagKey(hex(byLabel(s.sender).tag_secret))
    expect(toHex(await emailTag(tagKey, s.email, s.team_id, hex(s.recipient_key_id), hex(s.sealed_hash)))).toBe(s.email_tag)
    // The two kinds' tags never coincide: the same inputs under the name tag's label give another tag.
    expect(toHex(await nameTag(tagKey, s.email, s.team_id, hex(s.recipient_key_id), hex(s.sealed_hash)))).not.toBe(s.email_tag)
  })

  it.each(v.seals.map((s, i) => [i, s] as const))('seal %i opens for its recipient to the address exactly', async (_i, s) => {
    const email = await openEmail({
      teamId: s.team_id,
      senderId: s.sender_id,
      recipientId: s.recipient_id,
      sealed: hex(s.sealed),
      recipient: await identity(s.recipient),
      senderPublicKey: hex(byLabel(s.sender).public_key),
    })
    expect(email).toBe(s.email)
  })
})

describe('the negative vectors', () => {
  it.each(v.open_negatives.map((n) => [n.description, n] as const))('%s', async (_d, n) => {
    const attempt = openEmail({
      teamId: n.team_id,
      senderId: n.sender_id,
      recipientId: n.recipient_id,
      sealed: hex(n.sealed),
      recipient: await identity(n.opener),
      senderPublicKey: hex(n.sender_public_key),
    })
    switch (n.outcome) {
      case 'open_fails':
        await expect(attempt).rejects.toMatchObject({ code: 'team_names/open_failed' })
        break
      case 'refused_version':
        await expect(attempt).rejects.toMatchObject({ code: 'team_names/unsupported_version' })
        break
      case 'refused_length':
        await expect(attempt).rejects.toMatchObject({ code: 'team_names/malformed' })
        break
      case 'no_email':
        await expect(attempt).resolves.toBeNull()
        break
    }
  })

  it.each(v.address_negatives.map((n) => [n.description, n] as const))('an address with %s: the sealer refuses it and the opener shows nothing', async (_d, n) => {
    expect(n.outcome).toBe('no_email')
    // The row is a well-formed seal of exactly these bytes, so only the check can refuse what it opens to.
    expect(toHex(new TextEncoder().encode(n.email))).toBe(n.email_utf8)
    expect(layout(hex(n.email_utf8))).toBe(n.plaintext)
    expect(checkEmail(n.email)).toBeNull()

    // The sealer refuses the same address before anything is generated or derived.
    const senderLabel = v.identities.find((i) => i.user_id === n.sender_id)?.label
    if (!senderLabel) throw new Error(`no identity with id ${n.sender_id}`)
    const sender = await identity(senderLabel)
    const recipient = byLabel(n.opener)
    const generateKey = vi.spyOn(crypto.subtle, 'generateKey')
    const deriveBits = vi.spyOn(crypto.subtle, 'deriveBits')
    await expect(sealEmail({
      teamId: n.team_id, senderId: n.sender_id, recipientId: n.recipient_id, email: n.email, sender,
      recipientPublicKey: hex(recipient.public_key), recipientKeyId: hex(recipient.key_id),
    })).rejects.toMatchObject({ code: 'team_names/email_unsealable' })
    expect(generateKey).not.toHaveBeenCalled()
    expect(deriveBits).not.toHaveBeenCalled()
    vi.restoreAllMocks()

    await expect(openEmail({
      teamId: n.team_id,
      senderId: n.sender_id,
      recipientId: n.recipient_id,
      sealed: hex(n.sealed),
      recipient: await identity(n.opener),
      senderPublicKey: hex(n.sender_public_key),
    })).resolves.toBeNull()
  })

  it.each(v.cross_kind_negatives.map((n) => [n.description, n] as const))('%s', async (_d, n) => {
    const p = {
      teamId: n.team_id,
      senderId: n.sender_id,
      recipientId: n.recipient_id,
      sealed: hex(n.sealed),
      recipient: await identity(n.opener),
      senderPublicKey: hex(n.sender_public_key),
    }
    expect(n.sealed_as).not.toBe(n.open_as)
    // Its own kind opens it to the value, so the failure below is the label's and not a broken row.
    await expect(openAs(n.sealed_as, p)).resolves.toBe(n.value)
    expect(checkEmail(n.value)).toBe(n.value)
    await expect(openAs(n.open_as, p)).rejects.toMatchObject({ code: 'team_names/open_failed' })
  })

  it.each(v.tag_negatives.map((n) => [n.description, n] as const))('the tag differs for %s', async (_d, n) => {
    expect(sha256Hex(hex(n.sealed))).toBe(n.sealed_hash)
    const tag = await emailTag(await importTagKey(hex(n.tag_secret)), n.email, n.team_id, hex(n.recipient_key_id), hex(n.sealed_hash))
    expect(toHex(tag)).not.toBe(v.seals[n.row].email_tag)
  })

  it('carries both halves of the replay a stolen session can write (review M1)', async () => {
    // Found by shape, not by description: the row's own metadata over another ciphertext behind the same
    // version byte and enc (a row the server stores and nobody opens), and the row's own bytes in another team.
    const shapes = v.tag_negatives.map((n) => {
      const row = v.seals[n.row]
      const same = n.tag_secret === byLabel(row.sender).tag_secret && n.email === row.email && n.recipient_key_id === row.recipient_key_id
      const prefix = (h: string) => h.slice(0, 2 * (1 + 65))
      if (same && n.team_id === row.team_id && n.sealed.length === row.sealed.length && n.sealed !== row.sealed && prefix(n.sealed) === prefix(row.sealed)) return 'replaced'
      if (same && n.team_id !== row.team_id && n.sealed === row.sealed) return 'carried'
      return 'other'
    })
    expect(shapes).toContain('replaced')
    expect(shapes).toContain('carried')
    const replaced = v.tag_negatives[shapes.indexOf('replaced')]
    const row = v.seals[replaced.row]
    await expect(openEmail({
      teamId: row.team_id, senderId: row.sender_id, recipientId: row.recipient_id, sealed: hex(replaced.sealed),
      recipient: await identity(row.recipient), senderPublicKey: hex(byLabel(row.sender).public_key),
    })).rejects.toMatchObject({ code: 'team_names/open_failed' })
  })

  it('binds the address byte for byte: the same address in another case has another tag', async () => {
    const cased = v.tag_negatives.find((n) => n.email !== v.seals[n.row].email && n.email.toLowerCase() === v.seals[n.row].email.toLowerCase())
    if (!cased) throw new Error('no tag negative over the row’s address in another case')
    const row = v.seals[cased.row]
    expect([cased.tag_secret, cased.team_id, cased.recipient_key_id, cased.sealed]).toEqual([byLabel(row.sender).tag_secret, row.team_id, row.recipient_key_id, row.sealed])
    const tag = await emailTag(await importTagKey(hex(cased.tag_secret)), cased.email, cased.team_id, hex(cased.recipient_key_id), hex(cased.sealed_hash))
    expect(toHex(tag)).not.toBe(row.email_tag)
  })

  it('refuses a tag over a team id, key id or sealed hash of the wrong shape (review I2)', async () => {
    const s = v.seals[0]
    const tagKey = await importTagKey(hex(byLabel(s.sender).tag_secret))
    const keyId = hex(s.recipient_key_id)
    const sealedHash = hex(s.sealed_hash)
    await expect(emailTag(tagKey, s.email, s.team_id.replace(/-/g, ''), keyId, sealedHash)).rejects.toMatchObject({ code: 'team_names/invalid_id' })
    for (const [k, h] of [
      [keyId.slice(0, 31), sealedHash],
      [new Uint8Array([...keyId, 0]), sealedHash],
      [keyId, sealedHash.slice(0, 31)],
      [keyId, new Uint8Array([...sealedHash, 0])],
      [keyId, hex(s.enc)], // the row's enc where the hash belongs
    ]) {
      await expect(emailTag(tagKey, s.email, s.team_id, k, h)).rejects.toMatchObject({ code: 'team_names/malformed' })
    }
  })

  it('refuses an unknown version byte and a wrong size before any cryptography', async () => {
    const s = v.seals[0]
    const recipient = await identity(s.recipient)
    const derive = vi.spyOn(crypto.subtle, 'deriveBits')
    const importKey = vi.spyOn(crypto.subtle, 'importKey')
    const v2 = hex(s.sealed)
    v2[0] = 0x02
    const params = { teamId: s.team_id, senderId: s.sender_id, recipientId: s.recipient_id, recipient, senderPublicKey: hex(byLabel(s.sender).public_key) }
    await expect(openEmail({ ...params, sealed: v2 })).rejects.toMatchObject({ code: 'team_names/unsupported_version' })
    await expect(openEmail({ ...params, sealed: v2.slice(0, 100) })).rejects.toMatchObject({ code: 'team_names/unsupported_version' })
    await expect(openEmail({ ...params, sealed: hex(s.sealed).slice(0, 100) })).rejects.toMatchObject({ code: 'team_names/malformed' })
    // A refused version wins over a malformed id, as for names: nothing is read before the version byte.
    await expect(openEmail({ ...params, teamId: 'nope', sealed: v2 })).rejects.toMatchObject({ code: 'team_names/unsupported_version' })
    expect(derive).not.toHaveBeenCalled()
    expect(importKey).not.toHaveBeenCalled()
  })
})

describe('the address check (both sides run it)', () => {
  it('takes an address exactly as given: nothing folds case, normalises or trims', () => {
    for (const ok of [
      'a@b',
      'ada@example.com',
      'Ada.Lovelace@Example.COM',
      'ada+pulse@example.com',
      'zoé@example.com', // e and a combining acute (NFD): kept as it is, not composed
      'zöe@exämple.se',
      '用户@例子.广告',
      'rocket\u{1F680}@example.com',
      "!#$%&'*+-/=?^_`{|}~@example.com",
      '"quoted"@example.com',
      `${'x'.repeat(64)}@${'a'.repeat(63)}.${'b'.repeat(63)}.${'c'.repeat(57)}.com`,
    ]) {
      expect(checkEmail(ok), JSON.stringify(ok)).toBe(ok)
    }
  })

  it('counts UTF-8 bytes, not UTF-16 units: 254 bytes pass, 255 do not, whatever the characters', () => {
    const at = (local: string, domain: string) => `${local}@${domain}`
    expect(new TextEncoder().encode(at('é'.repeat(121), 'exämple.se')).length).toBe(254)
    expect(checkEmail(at('é'.repeat(121), 'exämple.se'))).not.toBeNull()
    expect(checkEmail(at('é'.repeat(121), 'exämples.se'))).toBeNull()
    // 84 three-byte characters: 252 bytes in 84 units, then '@' and one or two bytes of domain.
    expect(checkEmail(at('€'.repeat(84), 'x'))).not.toBeNull() // 254 bytes, 86 units
    expect(checkEmail(at('€'.repeat(84), 'xy'))).toBeNull() // 255 bytes, 87 units
    // 63 four-byte characters: 252 bytes in 126 units (surrogate pairs).
    expect(checkEmail(at('\u{1F680}'.repeat(63), 'x'))).not.toBeNull() // 254 bytes, 128 units
    expect(checkEmail(at('\u{1F680}'.repeat(63), 'xy'))).toBeNull() // 255 bytes, 129 units
  })

  it('refuses every whitespace, separator, control and format character, and a lone surrogate', () => {
    const refused: Record<string, string> = {
      tab: '\t', 'line feed': '\n', 'vertical tab': '\v', 'form feed': '\f', 'carriage return': '\r', space: ' ',
      NUL: '\u0000', escape: '\u001b', DEL: '\u007f', NEL: '\u0085', 'C1 control U+0090': '\u0090',
      'no-break space': ' ', 'ogham space': ' ', 'en quad': ' ', 'hair space': ' ',
      'narrow no-break space': ' ', 'medium mathematical space': ' ', 'ideographic space': '　',
      'line separator': ' ', 'paragraph separator': ' ',
      'soft hyphen': '­', 'Arabic letter mark': '؜', 'Mongolian vowel separator': '᠎',
      'zero-width space': '​', 'zero-width non-joiner': '‌', 'zero-width joiner': '‍',
      'left-to-right mark': '‎', 'right-to-left mark': '‏', 'right-to-left embedding': '‫',
      'right-to-left override': '‮', 'pop directional formatting': '‬', 'left-to-right isolate': '⁦',
      'first strong isolate': '⁨', 'pop directional isolate': '⁩', 'word joiner': '⁠',
      'byte order mark': '﻿', 'interlinear annotation anchor': '￹', 'language tag': '\u{e0001}',
      'tag latin small letter a': '\u{e0061}',
      'lone high surrogate': '\ud800', 'lone low surrogate': '\udfff',
    }
    for (const [what, c] of Object.entries(refused)) {
      for (const email of [`${c}ada@example.com`, `ada${c}@example.com`, `ada@exam${c}ple.com`, `ada@example.com${c}`]) {
        expect(checkEmail(email), `${what} in ${JSON.stringify(email)}`).toBeNull()
      }
    }
    // A surrogate PAIR is one character and passes; only a lone half is refused.
    expect(checkEmail('🚀@example.com')).toBe('\u{1F680}@example.com')
    expect(checkEmail('\ude80\ud83d@example.com')).toBeNull()
  })

  it('refuses invisible characters (default-ignorable code points), so an address cannot pass for another', async () => {
    const invisible: Record<string, string> = {
      'Hangul filler': '\u3164', 'Hangul choseong filler': '\u115f', 'halfwidth Hangul filler': '\uffa0',
      'variation selector 16': '\ufe0f', 'variation selector 1': '\ufe00', 'variation selector 17': '\u{e0100}',
      'combining grapheme joiner': '\u034f', 'Khmer vowel inherent aq': '\u17b4',
    }
    for (const [what, c] of Object.entries(invisible)) {
      for (const email of [`ada${c}@example.com`, `ada@exam${c}ple.com`]) {
        expect(checkEmail(email), `${what} in ${JSON.stringify(email)}`).toBeNull()
      }
    }
    const [d, e] = [await identity('D'), await identity('E')]
    await expect(
      sealEmail({ teamId: v.seals[0].team_id, senderId: byLabel('D').user_id, recipientId: byLabel('E').user_id, email: 'ad\u3164a@example.com', sender: d, recipientPublicKey: e.publicKey, recipientKeyId: e.keyId }),
    ).rejects.toMatchObject({ code: 'team_names/email_unsealable' })
  })

  it('refuses anything but exactly one U+0040 with something on each side', () => {
    for (const bad of ['', '@', 'ada', 'ada@', '@ada', 'a@b@c', 'ada@@example.com', '@@', 'ada＠example.com', 'ada﹫example.com']) {
      expect(checkEmail(bad), JSON.stringify(bad)).toBeNull()
    }
    expect(checkEmail(undefined as unknown as string)).toBeNull()
    expect(checkEmail(null as unknown as string)).toBeNull()
  })
})

describe('sealing and opening with keys made here', () => {
  it('round-trips an address exactly, under a fresh ephemeral key each time', async () => {
    const [d, e] = [await identity('D'), await identity('E')]
    const team = v.seals[0].team_id
    const [di, ei] = [byLabel('D').user_id, byLabel('E').user_id]
    for (const email of ['Ada.Lovelace@Example.COM', 'zoé@example.com', 'q@x']) {
      const a = await sealEmail({ teamId: team, senderId: di, recipientId: ei, email, sender: d, recipientPublicKey: e.publicKey, recipientKeyId: e.keyId })
      const b = await sealEmail({ teamId: team, senderId: di, recipientId: ei, email, sender: d, recipientPublicKey: e.publicKey, recipientKeyId: e.keyId })
      expect(a.sealed.length).toBe(SEALED_SIZE)
      expect(toHex(a.enc)).not.toBe(toHex(b.enc))
      expect(toHex(a.emailTag)).not.toBe(toHex(b.emailTag))
      const params = { teamId: team, senderId: di, recipientId: ei, recipient: e, senderPublicKey: d.publicKey }
      await expect(openEmail({ ...params, sealed: a.sealed })).resolves.toBe(email)
      // The tag recomputed over the row's own hash is the one the seal returned.
      expect(toHex(await emailTag(d.tagKey, email, team, e.keyId, hex(sha256Hex(a.sealed))))).toBe(toHex(a.emailTag))
      // An email row is not a name row, and the reverse, with keys made here too.
      await expect(openName({ ...params, sealed: a.sealed })).rejects.toMatchObject({ code: 'team_names/open_failed' })
    }
    const { sealed: nameRow } = await sealName({
      teamId: team, senderId: di, recipientId: ei, name: 'ada@example.com', sender: d, recipientPublicKey: e.publicKey, recipientKeyId: e.keyId,
    })
    const params = { teamId: team, senderId: di, recipientId: ei, recipient: e, senderPublicKey: d.publicKey, sealed: nameRow }
    await expect(openName(params)).resolves.toBe('ada@example.com')
    await expect(openEmail(params)).rejects.toMatchObject({ code: 'team_names/open_failed' })
  })

  it('a created key seals an address to another created key', async () => {
    const vmk = await crypto.subtle.importKey('raw', crypto.getRandomValues(new Uint8Array(32)), 'HKDF', false, ['deriveKey'])
    const vault = vaultOpsFor(vmk as VaultKey)
    const [me, them] = [(await createIdentity(vault)).identity, (await createIdentity(vault)).identity]
    const team = v.seals[0].team_id
    const [mi, ti] = [v.identities[0].user_id, v.identities[1].user_id]
    const { sealed } = await sealEmail({ teamId: team, senderId: mi, recipientId: ti, email: 'ada@example.com', sender: me, recipientPublicKey: them.publicKey, recipientKeyId: them.keyId })
    await expect(openEmail({ teamId: team, senderId: mi, recipientId: ti, sealed, recipient: them, senderPublicKey: me.publicKey })).resolves.toBe('ada@example.com')
  })
})

describe('error messages', () => {
  it('carry the code and never the address (review L8)', async () => {
    const secret = 'zoe.secretaddress@example.com'
    const errors: unknown[] = []
    const d = await identity('D')
    const e = byLabel('E')
    for (const email of [`${secret} `, `${secret}@`, `${'x'.repeat(250)}${secret}`]) {
      await sealEmail({
        teamId: v.seals[0].team_id, senderId: byLabel('D').user_id, recipientId: e.user_id, email, sender: d,
        recipientPublicKey: hex(e.public_key), recipientKeyId: hex(e.key_id),
      }).catch((err: unknown) => errors.push(err))
    }
    await sealEmail({
      teamId: 'nope', senderId: byLabel('D').user_id, recipientId: e.user_id, email: secret, sender: d,
      recipientPublicKey: hex(e.public_key), recipientKeyId: hex(e.key_id),
    }).catch((err: unknown) => errors.push(err))
    const s = v.seals[3]
    const flipped = hex(s.sealed)
    flipped[200] ^= 1
    await openEmail({ teamId: s.team_id, senderId: s.sender_id, recipientId: s.recipient_id, sealed: flipped, recipient: await identity(s.recipient), senderPublicKey: hex(byLabel(s.sender).public_key) })
      .catch((err: unknown) => errors.push(err))
    expect(errors).toHaveLength(5)
    expect(errors.map((err) => (err as TeamNamesError).code)).toEqual([
      'team_names/email_unsealable',
      'team_names/email_unsealable',
      'team_names/email_unsealable',
      'team_names/invalid_id',
      'team_names/open_failed',
    ])
    for (const err of errors) {
      expect(err).toBeInstanceOf(TeamNamesError)
      const te = err as TeamNamesError
      expect(te.message).toBe(te.code)
      expect(`${te.message} ${te.stack ?? ''}`).not.toContain('secretaddress')
      expect(`${te.message} ${te.stack ?? ''}`).not.toContain(s.email)
    }
  })
})
